-- 006 · 알림톡 문구 아홉 개의 첫 씨앗 · 발송 실패 사유 칸
--
-- 🔴 **문구의 정본은 `docs/alimtalk-templates.md`다.** 여기는 그 문서를 처음 한 번
--    DB에 옮겨 심는 자리일 뿐이다. 이미 적용된 마이그레이션은 다시 돌지 않으므로,
--    나중에 문구를 고칠 때 **이 파일을 따라 고치지 말 것** — 고치는 자리는
--    운영자 화면의 「문구 관리」(#38)이고, 카카오 심사에 내는 원본은 위 문서다.
--    (문구를 배포 없이 고칠 수 있게 하려고 DB에 두는 것이 결정 9다.)
--
-- ⚠️ 씨앗이 없으면 첫 신청이 들어온 순간 보낼 문구가 없어 **입금 안내가 안 나간다.**
--    그래서 심사 전이라도 행을 미리 세워 둔다. `approval='REG'`(등록만 함)이고
--    `template_code`는 비어 있다 — 승인 코드는 심사를 통과한 뒤 화면에서 적는다.
-- ═══════════════════════════════════════════════════════════════

-- ── 발송 실패 사유 ─────────────────────────────────────────────
-- 🔴 「보내다 실패한 것」 목록은 **왜** 실패했는지를 보여줘야 사람이 손을 쓸 수 있다.
--    `result_code`(웹훅 RESULT)에 섞어 적으면 「대행사가 준 코드」와 「우리가 판단한
--    이유」가 한 칸에서 뭉개진다 — 접수와 도달을 안 뭉친 것과 같은 이유로 따로 둔다.
alter table notification add column if not exists error text;

-- ── 문구 아홉 개 ───────────────────────────────────────────────
-- ⚠️ `auto_send`가 **둘**(①②)이다. ADR 003 §3의 표는 ①만 자동으로 적고 ②를 「운영자」로
--    적었는데, 같은 문서 §6의 흐름과 이슈 #31은 **자리가 찼을 때도 대기 안내가 자동으로
--    나간다**고 정한다(신청 응답에 이미 「대기로 접수됐다」가 실려 나가므로 사람이
--    나중에 손으로 보내면 그 사이 손님은 아무 소식도 못 받는다). 뒤의 것을 따랐다.
--    §3 표의 「운영자」는 **자리가 났을 때 ①을 다시 보내는 일**을 가리킨다.
-- ⚠️ 코드는 이 깃발이 아니라 **id로** 문구를 찾는다(`notification.ts`의 `TEMPLATE`).
--    깃발은 「문구 관리」 화면이 자동/수동을 표시하는 데 쓴다.
-- 🔴 **버튼 주소(`url_mobile`)에는 변수를 못 쓴다.** 그래서 여기에는 버튼의 이름과
--    종류만 적어 두고, 보낼 때 그 사람의 `#{링크}`를 통째로 넣는다(`notification.ts`).
-- 🔴 `sms_body`(대체문자)는 **일부러 비워 둔다.** 알림톡이 실패해 문자로 대체되면
--    90바이트뿐이라 본문을 그대로 쓸 수 없는데, **자동으로 자르면 문장 중간에서
--    끊긴다.** 비어 있는 동안에는 대체 발송을 아예 걸지 않는다 — 잘린 문장을 보내느니
--    안 보내는 편이 낫다. 소유자가 아홉 줄을 써서 「문구 관리」에 넣으면 그때 켜진다.
